-- Baseline schema, mirroring the tables the application already used in production.
-- Every statement is idempotent so it is a no-op on an existing database.

CREATE TABLE IF NOT EXISTS users (
    id            TEXT PRIMARY KEY DEFAULT gen_random_uuid()::text,
    username      TEXT UNIQUE NOT NULL,
    email         TEXT NOT NULL,
    password_hash TEXT,
    google_sub    TEXT UNIQUE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS video (
    id            TEXT PRIMARY KEY,
    video_url     TEXT,
    video_title   TEXT,
    video_summary TEXT,
    fav           BOOLEAN DEFAULT false,
    user_id       TEXT DEFAULT 'admin',
    created_at    TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS notes (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    video_timestamp TEXT,
    note            TEXT,
    note_source     TEXT DEFAULT 'user',
    video_id        TEXT NOT NULL REFERENCES video (id),
    user_id         TEXT DEFAULT 'admin'
);

CREATE TABLE IF NOT EXISTS label (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label_name TEXT,
    user_id    TEXT DEFAULT 'admin'
);

CREATE TABLE IF NOT EXISTS video_label (
    yt_video_id TEXT NOT NULL REFERENCES video (id),
    label_id    BIGINT NOT NULL REFERENCES label (id),
    CONSTRAINT pk_video_label PRIMARY KEY (yt_video_id, label_id)
);
