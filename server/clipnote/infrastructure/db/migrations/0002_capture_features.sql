-- Seconds-based timestamps, note types, async enrichment status, per-user
-- favourites and personal API tokens.

ALTER TABLE notes ADD COLUMN IF NOT EXISTS timestamp_seconds INTEGER;
ALTER TABLE notes ADD COLUMN IF NOT EXISTS note_type TEXT NOT NULL DEFAULT 'note';
ALTER TABLE notes ADD COLUMN IF NOT EXISTS status TEXT NOT NULL DEFAULT 'ready';
ALTER TABLE notes ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT now();

-- Backfill seconds from the legacy "mm:ss" / "h:mm:ss" display strings.
UPDATE notes
SET timestamp_seconds = CASE
    WHEN video_timestamp ~ '^\d+:\d{1,2}:\d{1,2}$' THEN
        split_part(video_timestamp, ':', 1)::int * 3600
        + split_part(video_timestamp, ':', 2)::int * 60
        + split_part(video_timestamp, ':', 3)::int
    WHEN video_timestamp ~ '^\d+:\d{1,2}$' THEN
        split_part(video_timestamp, ':', 1)::int * 60
        + split_part(video_timestamp, ':', 2)::int
    WHEN video_timestamp ~ '^\d+(\.\d+)?$' THEN
        round(video_timestamp::numeric)::int
END
WHERE timestamp_seconds IS NULL AND video_timestamp IS NOT NULL;

CREATE INDEX IF NOT EXISTS notes_user_video_idx ON notes (user_id, video_id);
CREATE INDEX IF NOT EXISTS notes_pending_idx ON notes (status) WHERE status = 'pending';

-- Favourites used to be a single global flag on video; make them per user.
CREATE TABLE IF NOT EXISTS user_video (
    user_id  TEXT NOT NULL,
    video_id TEXT NOT NULL REFERENCES video (id) ON DELETE CASCADE,
    fav      BOOLEAN NOT NULL DEFAULT false,
    PRIMARY KEY (user_id, video_id)
);

INSERT INTO user_video (user_id, video_id, fav)
SELECT DISTINCT n.user_id, n.video_id, true
FROM notes n
JOIN video v ON v.id = n.video_id
WHERE v.fav IS TRUE AND n.user_id IS NOT NULL
ON CONFLICT DO NOTHING;

CREATE TABLE IF NOT EXISTS api_tokens (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      TEXT NOT NULL,
    label        TEXT NOT NULL,
    scope        TEXT NOT NULL DEFAULT 'capture',
    token_hash   TEXT NOT NULL UNIQUE,
    token_prefix TEXT NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_used_at TIMESTAMPTZ,
    revoked_at   TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS api_tokens_user_idx ON api_tokens (user_id);
